// Каталог кризисов компаний (Биржа).
// Структура: вид кризиса -> 3+ сценария -> 2-3 варианта действий владельца,
// у каждого варианта — взвешенные исходы (сумма weight = 100) и исход по таймауту.
// Ограничения каталога (проверяются тестом tests/crisisCatalog.test.ts):
//  - потеря <= CRISIS_MAX_LOSS_BPS (2500 bps), прибыль <= CRISIS_MAX_GAIN_BPS (1500 bps);
//  - EV вариантов одного сценария расходятся не более чем на 300 bps (3 п.п.),
//    чтобы выбор между надёжным и рискованным был реальным;
//  - EV исхода по таймауту СТРОГО хуже EV любого варианта (молчание — худший исход).
// Лимиты bps: keep in sync with worker/src/exchange/constants.ts.

export interface CrisisOutcome {
  /** Вес исхода внутри варианта; сумма по варианту = 100. */
  weight: number;
  /** Изменение казны в bps от текущей казны (отрицательное = потеря). */
  pct_bps: number;
  /** Текст исхода для владельца и ленты. */
  text: string;
}

export interface CrisisOption {
  /** Короткий id без двоеточий (попадает в custom_id кнопки). */
  id: string;
  /** Подпись кнопки (лимит Discord — 80 символов). */
  label: string;
  emoji: string;
  outcomes: CrisisOutcome[];
}

export interface CrisisScenario {
  kind: CrisisKind;
  scenario_text: string;
  options: CrisisOption[];
  timeout: CrisisOutcome;
}

